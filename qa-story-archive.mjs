import assert from 'node:assert/strict';
import { AdventureArchive, ARCHIVE_STORAGE_KEY } from './dist/adventure-archive.js';
import { CombatBuild } from './dist/combat-build.js';
import { archivePanelHTML } from './dist/archive-panel.js';

const values=new Map(),storage={getItem:key=>values.get(key)??null,setItem:(key,value)=>values.set(key,value)};
const archive=new AdventureArchive({storage});
const create=()=>({difficulty:'normal',player:{level:1},build:new CombatBuild(),runTime:0,kills:0,bossKills:0,story:{id:'prologue',completed:false}});
const g=create();archive.begin(g);
assert.equal(archive.recordStoryCompletion(g),false,'An unfinished chapter cannot be recorded');
g.canonicalBuild=g.build;g.build=CombatBuild.fromSnapshot(g.build.serialize());
g.build.weapons.sword.baseRank=5;g.build.skills.barrier.baseRank=5;
archive.checkpoint(g,{force:true});
assert.equal(archive.data.entries['weapon:sword'].maxLevel,1,'Temporary weapon ranks never enter the archive');
assert.equal(archive.data.entries['skill:barrier'],undefined,'Temporary skills do not become permanently discovered');
g.story.completed=true;g.story.completionTime=120;g.runTime=125;
assert(archive.recordStoryCompletion(g));assert.equal(archive.recordStoryCompletion(g),false);
archive.checkpoint(g,{force:true});archive.finish(g,'quit');
assert.deepEqual(archive.data.stories.prologue,{clears:1,bestTime:120,lastTime:120});
const replay=create();archive.begin(replay);replay.story.completed=true;replay.runTime=130;archive.checkpoint(replay,{force:true});
assert.deepEqual(archive.data.stories.prologue,{clears:2,bestTime:120,lastTime:130});
assert.match(archivePanelHTML(archive.data,{tab:'records'}),/剧情记录/);
assert.match(archivePanelHTML(archive.data,{tab:'records'}),/data-story-record="prologue"/);
assert.deepEqual(new AdventureArchive({storage}).data.stories,archive.data.stories);
const legacyData={...archive.data,version:2};delete legacyData.stories;
const oldValues=new Map([['wild-echoes-adventure-archive-v2',JSON.stringify(legacyData)]]);
const migrated=new AdventureArchive({storage:{getItem:key=>oldValues.get(key)??null,setItem:(key,value)=>oldValues.set(key,value)}});
assert.equal(migrated.data.version,3);assert(oldValues.has(ARCHIVE_STORAGE_KEY));
assert.equal(migrated.data.totals.runs,archive.data.totals.runs);assert.deepEqual(migrated.data.stories,{});
console.log('Story archive: completion/replay, canonical build, v2 migration and records UI passed.');
