import assert from 'node:assert/strict';
import { Game } from './dist/engine.js';
import { STAGES } from './dist/stage-definitions.js';
import { groundOffset } from './dist/terrain.js';
import { portalDoor } from './dist/portal-geometry.js';
import { AdventureArchive } from './dist/adventure-archive.js';
import { WorldMap } from './dist/world-map.js';

let seed=819381;Math.random=()=>((seed=(Math.imul(seed,1664525)+1013904223)>>>0)/4294967296);
const place=(game,point)=>{game.player.x=point.x;game.player.y=point.y-groundOffset(game.player,true);};
const quiet=game=>{game.player.xpNext=game.crystalsNext=Infinity;game.player.invuln=Infinity;game._shot=Infinity;};
const archive=new AdventureArchive({storage:null});
for(const stage of STAGES){
  const game=new Game({stageId:stage.id}),run=game.stage,scene=game.mapId,terrain=game.terrain,boss=run.boss;
  quiet(game);archive.begin(game);
  assert.equal(game.mode,'dungeon');assert.equal(scene,stage.mapId);assert.equal(game.region.id,stage.worldMapId);
  assert.equal(game.enemies.filter(enemy=>enemy.stageBoss).length,1);assert.equal(boss.maxHp,stage.boss.hp);assert.equal(boss.bossKind,stage.boss.kind);
  assert.equal(run.bossDefeated,false);assert.equal(run.complete(),false);assert.equal(run.openExit(),null);
  assert.equal(game.regions.portals.length,0);assert.equal(game.regions.states.size,0);
  assert.equal(game.enterPortal('portal:forest-outer:forest-heart'),false,'removed island routes cannot switch the challenge scene');
  assert.equal(game.stage.onBossKilled({...boss,hp:0}),null,'a different enemy cannot complete the objective');
  assert.equal(game._hurtEnemy(boss,boss.hp+1),0,'the arena cannot be cleared by a remote attack from spawn');
  const map=new WorldMap(),guide=run.getGuide();assert(guide?.target);
  assert.equal(guide.target.x,stage.arena.x);assert.equal(guide.target.y,stage.arena.y);
  assert(map.getMarkers(game,{range:30000}).some(marker=>marker.id===boss.id&&marker.x===boss.x&&marker.y===boss.y),'the actual Boss destination appears on the map');
  game.regionGrace=0;game._spawn=0;game.update(.05);
  assert(game.enemies.some(enemy=>!enemy.stageBoss&&!enemy.debugBoss),'the trial supplies combat enemies without world territories');
  place(game,{x:stage.arena.x,y:stage.arena.y+140});run.update();assert(run.bossEngaged);
  const engagedIds=new Set(game.enemies.map(enemy=>enemy.id));game._spawn=0;game.update(.05);
  assert(game.enemies.every(enemy=>engagedIds.has(enemy.id)),'engaging the Boss pauses ambient arrivals');
  const spawn=terrain.island.layout.spawn;place(game,spawn);run.update();assert.equal(run.bossEngaged,false);
  assert.deepEqual(boss.guardReturnTarget,boss.stageHome,'leaving the arena makes the Boss return home');
  assert.equal(game._hurtEnemy(boss,boss.hp+1),0,'retreating outside the arena disables remote damage');
  place(game,{x:stage.arena.x,y:stage.arena.y+140});run.update();assert(run.bossEngaged);
  const resources={gold:game.gold,crystals:game.crystals};
  assert(game._hurtEnemy(boss,boss.hp+1)>0);assert(run.bossDefeated);assert.equal(run.completed,false);
  assert(game.gold>=resources.gold+stage.reward.gold);assert(game.crystals>=resources.crystals+stage.reward.crystals);
  const earned={gold:game.gold,crystals:game.crystals,kills:game.kills};
  assert.equal(run.onBossKilled(boss),null);assert.deepEqual({gold:game.gold,crystals:game.crystals,kills:game.kills},earned,'the objective cannot award resources twice');
  const exit=game.regions.portals.find(portal=>portal.kind==='victory');assert(exit);assert.equal(game.regions.portals.length,1);
  assert.equal(exit.x,stage.exit.x);assert.equal(exit.y,stage.exit.y);assert.equal(run.openExit(),exit);
  assert(game.terrain===terrain,'the trial retains its terrain instance');assert.equal(game.mapId,scene,'Boss defeat never swaps to another island');
  game.regions.flushReward();assert.equal(game.status,'super');place(game,portalDoor(exit));
  assert.equal(run.complete(),false,'resolve the upgrade reward before leaving');
  assert(game.chooseSuper(game.getSuperChoices()[0].id));assert(run.rewardClaimed);
  place(game,{x:stage.arena.x,y:stage.arena.y+140});
  const remainingIds=new Set(game.enemies.map(enemy=>enemy.id)),waves=game.waveDirector.count;
  game._spawn=0;game.update(.05);
  assert(game.enemies.every(enemy=>remainingIds.has(enemy.id)),'no ambient arrivals after the Boss is defeated');assert.equal(game.waveDirector.count,waves,'no new wave starts during evacuation');
  const exitGuide=run.getGuide();assert(exitGuide?.target);assert.deepEqual(exitGuide.target,portalDoor(exit));
  assert(map.getMarkers(game,{range:30000}).some(marker=>marker.kind==='victory'||marker.x===exitGuide.target.x&&marker.y===exitGuide.target.y));
  place(game,portalDoor(exit));
  for(const status of ['paused','dead']){game.status=status;assert.equal(run.complete(),false);}
  game.status='playing';assert(game.touchInteractions.update(),'ordinary doorway contact completes the trial');
  assert.equal(game.status,'victory');assert(run.completed);assert.equal(run.getGuide(),null);
  assert.equal(game.sceneTransition.active,false);assert.equal(game.regions.states.size,0,'a single-scene trial creates no travel snapshots');
  const after={gold:game.gold,crystals:game.crystals,time:game.runTime};assert.equal(run.complete(),false);game.update(.05);
  assert.deepEqual({gold:game.gold,crystals:game.crystals,time:game.runTime},after);
  const report=archive.finish(game,'victory');assert.equal(report.stageCompletion.id,stage.id);
  archive.finish(game,'victory');assert.equal(archive.data.stages[stage.id].normal.clears,1);
  const fresh=new Game({stageId:stage.id});assert.equal(fresh.stage.bossDefeated,false);assert.equal(fresh.stage.completed,false);assert.equal(fresh.stage.rewardClaimed,false);assert.equal(fresh.regions.portals.length,0);
  assert(fresh.stage.boss!==boss,'a new run owns a different Boss instance');assert.equal(fresh.stage.boss.hp,stage.boss.hp);
}
assert.deepEqual(new Set(Object.keys(archive.data.stages)),new Set(STAGES.map(stage=>stage.id)));
const casual=new Game({stageId:STAGES[0].id,difficulty:'casual'});assert.equal(casual.stage.boss.maxHp,STAGES[0].boss.easyHp);
const dead=new Game({stageId:STAGES[0].id});archive.begin(dead);dead.status='dead';assert.equal(dead.stage.complete(),false);assert.equal(archive.finish(dead,'death').stageCompletion,null);
console.log('All stage flow: eight single-scene starts, independent combat and Boss activation/retreat, one-shot rewards, stopped evacuation spawning, contact victory, fresh restarts and isolated archive clears passed.');
