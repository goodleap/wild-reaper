import assert from 'node:assert/strict';
import { STAGES, getStageDefinition } from './dist/stage-definitions.js';
import { defineStage } from './dist/stages/define-stage.js';
import { StageRun } from './dist/stage-run.js';
import { WORLD_IDS, worldForId } from './dist/world-definitions.js';
import { initBoss } from './dist/bosses.js';
import { getConfigSnapshot } from './dist/content-config.js';
import { validateContentPack } from './dist/content-schema.js';

const ids=['forest','marsh','ruins','beach','city','mountain','snow','volcano'].map(id=>`${id}-trial`);
const worlds=['rift-forest','marsh','ruins','beach','clockshadow-city','mountain','snow','ember-realm-large'];
assert.deepEqual(STAGES.map(stage=>stage.id),ids,'the eight trial identities remain available');
assert.deepEqual(STAGES.map(stage=>stage.worldMapId),worlds,'trials borrow the current polished maps');
assert.equal(getStageDefinition('forest'),null);assert.equal(getStageDefinition('removed-stage'),null);
assert.equal(new Set(STAGES.map(stage=>stage.mapId)).size,8,'each single-scene trial owns a separate run identity');
for(const stage of STAGES){
  const world=worldForId(stage.worldMapId),source=getConfigSnapshot().sections.stages.definitions.find(item=>item.id===stage.id);
  assert.equal(getStageDefinition(stage.id),stage);assert.equal(stage.worldIndex,WORLD_IDS.indexOf(stage.worldMapId));
  assert.equal(stage.mapId,`${stage.id}:challenge`);assert.equal(stage.seed,world.seed??stage.worldIndex);
  assert.equal(stage.color,world.colors.accent);assert.equal(stage.dangerFactor,world.danger);
  assert(stage.name&&stage.shortName&&stage.summary&&stage.difficultyLabel&&stage.sceneName);
  assert(Object.isFrozen(stage)&&Object.isFrozen(stage.boss)&&Object.isFrozen(stage.reward)&&Object.isFrozen(stage.arena));
  for(const key of ['islands','themeId','themeIndex','outer','core','startMapId','coreMapId','coreReward'])assert.equal(Object.hasOwn(stage,key),false,`${key} belongs to the removed two-island format`);
  assert(world.authored.areas.some(area=>area.id===stage.arena.areaId),'the arena refers to a real area on its source map');
  assert.deepEqual(stage.boss,source.boss);assert.deepEqual(stage.reward,source.reward);
  for(const point of [stage.arena,stage.exit])for(const key of ['x','y'])assert(Number.isFinite(point[key]));
  assert(stage.boss.hp>=stage.boss.easyHp&&stage.boss.hp>0&&stage.reward.gold>0&&stage.reward.crystals>0);
  assert.equal(initBoss({type:'boss',bossIndex:stage.boss.index},stage.boss.kind).bossKind,stage.boss.kind);
  const first=new StageRun({},stage.id),second=new StageRun({},stage.id);
  assert.equal(first.currentMapId,stage.mapId);assert.equal(first.sceneName,stage.sceneName);assert.equal(first.seed,stage.seed);
  assert.equal(first.bossDefeated,false);assert.equal(first.bossEngaged,false);assert.equal(first.completed,false);
  for(const key of ['currentIsland','isBossIsland','coreDefeated','island'])assert.equal(key in first,false,'the retired island API is not kept as a compatibility layer');
  first.completed=true;assert.equal(second.completed,false,'run state is never stored on shared definitions');
}
assert.equal(STAGES[0].worldMapId,'rift-forest','the commemorative forest remains exclusive to its separate survival mode');
assert.equal(getStageDefinition('verdant-rift-trial'),null);
const recipe=getConfigSnapshot().sections.stages.definitions[0];
assert.throws(()=>defineStage({...recipe,worldMapId:'missing'}));
const alternative=defineStage({...recipe,id:'forest-expedition'});
assert.equal(alternative.worldMapId,recipe.worldMapId);assert.notEqual(alternative.mapId,STAGES[0].mapId);
const reject=(edit,label)=>{const pack=structuredClone(getConfigSnapshot());edit(pack.sections.stages.definitions);assert.throws(()=>validateContentPack(pack),undefined,label);};
reject(stages=>stages[0].worldMapId='forest','an unpolished natural island cannot replace an authored challenge map');
reject(stages=>stages[0].worldMapId='missing','unknown source map');
reject(stages=>stages[0].arena.areaId='missing','unknown arena area');
reject(stages=>stages[0].arena.x=Infinity,'finite arena');
reject(stages=>stages[0].exit.x=1e9,'exit inside its source map');
reject(stages=>stages[0].boss.kind='missing','known Boss behavior');
reject(stages=>stages[0].boss.hp=-1,'positive Boss strength');
reject(stages=>stages[0].reward.gold=-1,'nonnegative reward');
reject(stages=>stages[1].id=stages[0].id,'unique trial identity');
console.log('Stage catalog: eight independent single-scene challenges, current shared map sources, separate run state and invalid-map/arena/Boss/reward rejection passed.');
